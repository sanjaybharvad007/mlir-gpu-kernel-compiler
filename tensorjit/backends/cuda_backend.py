BM, BN, BK = 64, 64, 16


def _epilogue_lines(g: _Gen, out_shape, bidx) -> list[str]:
    k = g.k
    mm = k.anchor
    a, b = mm.inputs
    epilogue = [n for n in k.nodes if n is not mm]
    out_idx = list(bidx) + ["i", "j"]
    tail = []
    for n in k.inputs:
        if n is a or n is b:
            continue
        consumer = next((c for c in epilogue if n in c.inputs), epilogue[0])
        tail.append(_load(g, n, consumer, out_shape, out_idx))
    tail += _body(g, epilogue)
    cs = contiguous_strides(out_shape)
    for jj, o in enumerate(k.outputs):
        tail.append(_store(g, jj, o, g.names[id(o)], index_expr(out_idx, cs)))
    return tail


def gen_matmul(g: _Gen) -> tuple[str, Launch]:
    k = g.k
    mm = k.anchor
    a, b = mm.inputs
    M, K = a.shape[-2], a.shape[-1]
    tb = bool(mm.attrs.get("trans_b"))
    N = b.shape[-2] if tb else b.shape[-1]
    out_shape = mm.shape
    batch_shape = out_shape[:-2]
    batch = math.prod(batch_shape) if batch_shape else 1
    TA, TB = CTYPE[a.dtype], CTYPE[b.dtype]

    def bstrides(t: Node):
        cs = contiguous_strides(t.shape)
        pad = len(batch_shape) - (len(t.shape) - 2)
        st = [0] * pad
        for d in range(len(t.shape) - 2):
            st.append(0 if t.shape[d] == 1 and batch_shape[pad + d] != 1 else cs[d])
        return tuple(st)

    dec, bidx = decompose("bi", batch_shape, "b") if batch_shape else ([], [])
    a_off = index_expr(bidx, bstrides(a)) if batch_shape else "0"
    b_off = index_expr(bidx, bstrides(b)) if batch_shape else "0"
    A, B = g.names[id(a)], g.names[id(b)]
    b_elem = (lambda kk, j: f"{B}b[({j}) * {K} + ({kk})]") if tb else (lambda kk, j: f"{B}b[({kk}) * {N} + ({j})]")

    # WMMA tiles are loaded without bounds checks: the block tile (64x64) and the K step (16)
    # must divide the problem exactly; everything else takes the bounds-checked SIMT path.
    use_wmma = (a.dtype in (DType.f16, DType.bf16) and a.dtype == b.dtype and M % BM == 0 and N % BN == 0
                and K % BK == 0 and os.environ.get("TENSORJIT_CUDA_WMMA", "1") == "1")

    L = [f'extern "C" __global__ void kernel_{g.idx}({g.params()}) {{']
    L.append("  const long bi = blockIdx.z;")
    L += ["  " + s for s in dec]
    L.append(f"  const {TA}* __restrict__ {A}b = {A}_p + ({a_off});")
    L.append(f"  const {TB}* __restrict__ {B}b = {B}_p + ({b_off});")
    L.append(f"  const int i0 = blockIdx.y * {BM}, j0 = blockIdx.x * {BN};")
    L.append("  const int tid = threadIdx.x;")
    if use_wmma:
        wtype = "half" if a.dtype == DType.f16 else "__nv_bfloat16"
        L.append("  using namespace nvcuda;")
        L.append(f"  __shared__ __align__(32) {wtype} As[{BM}][{BK} + 8];")
        L.append(f"  __shared__ __align__(32) {wtype} Bs[{BN if tb else BK}][{BK if tb else BN} + 8];")
        L.append(f"  __shared__ __align__(32) float Cs[{BM}][{BN} + 4];")
        L.append("  const int warp = tid >> 5, wm = warp >> 1, wn = warp & 1;   // 4 warps: 2x2 of 32x32")
        L.append("  wmma::fragment<wmma::accumulator, 16, 16, 16, float> acc[2][2];")
        L.append("  for (int x = 0; x < 2; ++x) for (int y = 0; y < 2; ++y) wmma::fill_fragment(acc[x][y], 0.0f);")
        L.append(f"  for (int k0 = 0; k0 < {K}; k0 += {BK}) {{")
        L.append(f"    for (int t = tid; t < {BM * BK}; t += 128) {{ const int r = t / {BK}, c = t % {BK}; As[r][c] = {A}b[(i0 + r) * {K} + k0 + c]; }}")
        if tb:
            L.append(f"    for (int t = tid; t < {BN * BK}; t += 128) {{ const int r = t / {BK}, c = t % {BK}; Bs[r][c] = {B}b[(j0 + r) * {K} + k0 + c]; }}")
        else:
            L.append(f"    for (int t = tid; t < {BK * BN}; t += 128) {{ const int r = t / {BN}, c = t % {BN}; Bs[r][c] = {B}b[(k0 + r) * {N} + j0 + c]; }}")
        L.append("    __syncthreads();")
        L.append(f"    wmma::fragment<wmma::matrix_a, 16, 16, 16, {wtype}, wmma::row_major> fa[2];")
        L.append(f"    wmma::fragment<wmma::matrix_b, 16, 16, 16, {wtype}, {'wmma::col_major' if tb else 'wmma::row_major'}> fb[2];")
        L.append(f"    for (int x = 0; x < 2; ++x) wmma::load_matrix_sync(fa[x], &As[wm * 32 + x * 16][0], {BK} + 8);")
        if tb:
            L.append(f"    for (int y = 0; y < 2; ++y) wmma::load_matrix_sync(fb[y], &Bs[wn * 32 + y * 16][0], {BK} + 8);")
        else:
            L.append(f"    for (int y = 0; y < 2; ++y) wmma::load_matrix_sync(fb[y], &Bs[0][wn * 32 + y * 16], {BN} + 8);")
        L.append("    for (int x = 0; x < 2; ++x) for (int y = 0; y < 2; ++y) wmma::mma_sync(acc[x][y], fa[x], fb[y], acc[x][y]);")
        L.append("    __syncthreads();")
        L.append("  }")
        L.append(f"  for (int x = 0; x < 2; ++x) for (int y = 0; y < 2; ++y) wmma::store_matrix_sync(&Cs[wm * 32 + x * 16][wn * 32 + y * 16], acc[x][y], {BN} + 4, wmma::mem_row_major);")
        L.append("  __syncthreads();")
        L.append(f"  for (int t = tid; t < {BM * BN}; t += 128) {{")
        L.append(f"    const int ii = t / {BN}, jj = t % {BN};")
        L.append("    const long i = i0 + ii, j = j0 + jj;")
        L.append(f"    const float {g.names[id(mm)]} = Cs[ii][jj];")
        L += ["    " + s for s in _epilogue_lines(g, out_shape, bidx)]
        L.append("  }")
        L.append("}")
        grid = (N // BN, M // BM, batch)
        return "\n".join(L), Launch(f"kernel_{g.idx}", grid, (128, 1, 1))

    # SIMT path: 256 threads, each owns a 4x4 micro-tile of the 64x64 block tile.
    L.append(f"  __shared__ float As[{BK}][{BM} + 4];   // transposed: As[k][i]")
    L.append(f"  __shared__ float Bs[{BK}][{BN} + 4];")
    L.append("  const int tr = tid / 16, tc = tid % 16;        // thread tile origin: (tr*4, tc*4)")
    L.append("  float acc[4][4] = {};")
    L.append(f"  for (int k0 = 0; k0 < {K}; k0 += {BK}) {{")
    L.append(f"    for (int t = tid; t < {BM * BK}; t += 256) {{")
    L.append(f"      const int r = t / {BK}, c = t % {BK};")
    L.append("      const int gi = i0 + r, gk = k0 + c;")
    L.append(f"      As[c][r] = (gi < {M} && gk < {K}) ? tj_to_f32({A}b[(long)gi * {K} + gk]) : 0.0f;")
    L.append("    }")
    L.append(f"    for (int t = tid; t < {BK * BN}; t += 256) {{")
    L.append(f"      const int r = t / {BN}, c = t % {BN};")
    L.append("      const int gk = k0 + r, gj = j0 + c;")
    L.append(f"      Bs[r][c] = (gk < {K} && gj < {N}) ? tj_to_f32({b_elem('gk', 'gj')}) : 0.0f;")
    L.append("    }")
    L.append("    __syncthreads();")
    L.append("    #pragma unroll")
    L.append(f"    for (int kk = 0; kk < {BK}; ++kk) {{")
    L.append("      float av[4], bv[4];")
    L.append("      for (int x = 0; x < 4; ++x) av[x] = As[kk][tr * 4 + x];")
    L.append("      for (int y = 0; y < 4; ++y) bv[y] = Bs[kk][tc * 4 + y];")
    L.append("      for (int x = 0; x < 4; ++x) for (int y = 0; y < 4; ++y) acc[x][y] = fmaf(av[x], bv[y], acc[x][y]);")
    L.append("    }")
    L.append("    __syncthreads();")
    L.append("  }")
    L.append("  for (int x = 0; x < 4; ++x) for (int y = 0; y < 4; ++y) {")
    L.append("    const long i = i0 + tr * 4 + x, j = j0 + tc * 4 + y;")
    L.append(f"    if (i < {M} && j < {N}) {{")
    L.append(f"      const float {g.names[id(mm)]} = acc[x][y];")
    L += ["      " + s for s in _epilogue_lines(g, out_shape, bidx)]
    L.append("    }")
    L.append("  }")
    L.append("}")
    grid = ((N + BN - 1) // BN, (M + BM - 1) // BM, batch)
    return "\n".join(L), Launch(f"kernel_{g.idx}", grid, (256, 1, 1))


