def generate(program: Program) -> tuple[str, list[Launch]]:
    sources, launches = [PRELUDE], []
    for idx, k in enumerate(program.kernels):
        names = {id(n): f"in{j}" for j, n in enumerate(k.inputs)}
        names.update({id(n): f"v{j}" for j, n in enumerate(k.nodes)})
        g = _Gen(k, idx, names)
        if k.kind in ("elementwise", "copy"):
            src, launch = gen_elementwise(g)
        elif k.kind == "row":
            src, launch = gen_row(g, k.stages, tuple(k.rows), k.n)  # type: ignore[attr-defined]
        elif k.kind == "reduce":
            x = k.anchor.inputs[0]
            src, launch = gen_row(g, [k], tuple(x.shape[:-1]), x.shape[-1])
        elif k.kind == "matmul":
            src, launch = gen_matmul(g)
        else:
            raise NotImplementedError(k.kind)
        sources.append(src)
        launches.append(launch)
    return "\n\n".join(sources), launches


class CudaProgram:
    """Executes a program through NVRTC-compiled kernels; optionally as one CUDA graph."""

    def __init__(self, program: Program, device: str = "cuda", use_graph: bool | None = None):
        from . import cuda_driver as drv

        self.program = program
        self.device = torch.device(device)
        self.backend = "cuda"
        self.source, self.launches = generate(program)
        self.plan: MemoryPlan = plan_memory(program)
        tag = content_hash(self.source, "cuda-v1")
        path = cache_dir() / f"tj_cuda_{tag}.cu"
        if not path.exists():
            path.write_text(self.source)
        ptx_path = cache_dir() / f"tj_cuda_{tag}_{'_'.join(map(str, drv.compute_capability()))}.ptx"
        if ptx_path.exists():
            ptx = ptx_path.read_bytes()
        else:
            ptx = drv.compile_to_ptx(self.source, name=path.name)
            ptx_path.write_bytes(ptx)
        self.module = drv.Module(ptx)
        self.arena = torch.empty(max(self.plan.arena_bytes, 1), dtype=torch.uint8, device=self.device)
        g = program.graph
        self._aliases = program.aliases
        escaping = {id(self._resolve(o)) for o in g.outputs}
        self._out_nodes = [o for k in program.kernels for o in k.outputs if id(o) in escaping]
        self.pool = BufferPool()
        self.use_graph = (os.environ.get("TENSORJIT_CUDA_GRAPH", "1") == "1") if use_graph is None else use_graph
        self._graph = None
        self._static_in: list[torch.Tensor] | None = None
        self._static_out: list[torch.Tensor] | None = None
        self.stats = {"calls": 0, "graph_replays": 0}

    @property
    def num_kernels(self) -> int:
        return len(self.launches)

    def _resolve(self, n: Node) -> Node:
        while id(n) in self._aliases:
            n = self._aliases[id(n)][0]
        return n

    def _ptr(self, n: Node, env: dict[int, torch.Tensor]) -> int:
        src = self._resolve(n)
        if id(src) in env:
            return env[id(src)].data_ptr()
        off = self.plan.offset(src)
        if off is None:
            raise RuntimeError(f"{n.name} has no storage")
        return self.arena.data_ptr() + off

    def _launch_all(self, env: dict[int, torch.Tensor], stream: int | None = None) -> None:
        for k, launch in zip(self.program.kernels, self.launches):
            args = [self._ptr(i, env) for i in k.inputs] + [self._ptr(o, env) for o in k.outputs]
            self.module.launch(launch.name, launch.grid, launch.block, args, launch.shared, stream)

    def __call__(self, *inputs: torch.Tensor) -> list[torch.Tensor]:
        from . import cuda_driver as drv

        g = self.program.graph
        ins = [t.contiguous() for t in inputs]
        self.stats["calls"] += 1
        if self.use_graph:
            if self._graph is None:
                # static buffers: the graph bakes in pointers, so inputs are copied in and outputs cloned out
                self._static_in = [t.clone() for t in ins]
                self._static_out = [torch.empty(o.shape, dtype=TORCH_DTYPE[o.dtype], device=self.device) for o in self._out_nodes]
                env = {id(n): t for n, t in zip(g.inputs, self._static_in)}
                env.update({id(o): t for o, t in zip(self._out_nodes, self._static_out)})
                self._graph = drv.Graph()
                self._graph.capture(lambda s: self._launch_all(env, s))
            for dst, src in zip(self._static_in, ins):
                dst.copy_(src)
            self._graph.launch()
            self.stats["graph_replays"] += 1
            outs = [t.clone() for t in self._static_out]
        else:
            outs = [self.pool.take_output(o.shape, TORCH_DTYPE[o.dtype], "cuda") for o in self._out_nodes]
            env = {id(n): t for n, t in zip(g.inputs, ins)}
            env.update({id(o): t for o, t in zip(self._out_nodes, outs)})
            self._launch_all(env)
        env = {id(o): t for o, t in zip(self._out_nodes, outs)}
        env.update({id(n): t for n, t in zip(g.inputs, ins)})
        result = []
        for o in g.outputs:
            src = self._resolve(o)
            if id(src) in env:
                t = env[id(src)]
            elif src.op == "const":
                t = torch.full(src.shape, src.attrs["value"], dtype=TORCH_DTYPE[src.dtype], device=self.device)
            else:
                raise RuntimeError(f"output {o.name} was not produced")
            result.append(t.reshape(o.shape) if tuple(t.shape) != tuple(o.shape) else t)
        return result


def compile_program(program: Program, device: str = "cuda", tune: bool = True) -> CudaProgram:
    return CudaProgram(program, device=device)
