CTYPE = {DType.f32: "float", DType.f16: "__half", DType.bf16: "__nv_bfloat16", DType.i32: "int"}

PRELUDE = r"""
// generated by tensorjit (CUDA backend)
#ifndef TJ_HOST_STUB
#include <cuda_fp16.h>
#include <cuda_bf16.h>
#include <mma.h>
#endif
#define TJ_MIN(a, b) ((a) < (b) ? (a) : (b))

__device__ __forceinline__ float tj_to_f32(float x) { return x; }
__device__ __forceinline__ float tj_to_f32(int x) { return (float)x; }
__device__ __forceinline__ float tj_to_f32(__half x) { return __half2float(x); }
__device__ __forceinline__ float tj_to_f32(__nv_bfloat16 x) { return __bfloat162float(x); }
template <typename T> __device__ __forceinline__ T tj_from_f32(float x);
template <> __device__ __forceinline__ float tj_from_f32<float>(float x) { return x; }
template <> __device__ __forceinline__ int tj_from_f32<int>(float x) { return (int)x; }
template <> __device__ __forceinline__ __half tj_from_f32<__half>(float x) { return __float2half(x); }
template <> __device__ __forceinline__ __nv_bfloat16 tj_from_f32<__nv_bfloat16>(float x) { return __float2bfloat16(x); }

__device__ __forceinline__ float tj_warp_sum(float v) {
  for (int o = 16; o > 0; o >>= 1) v += __shfl_xor_sync(0xffffffffu, v, o);
  return v;
}
__device__ __forceinline__ float tj_warp_max(float v) {
  for (int o = 16; o > 0; o >>= 1) v = fmaxf(v, __shfl_xor_sync(0xffffffffu, v, o));
  return v;
}
// Block-wide reduction; every thread receives the result.  `red` must be a
// __shared__ float[32]; the call must be reached by all threads.
__device__ __forceinline__ float tj_block_sum(float v, float* red) {
  v = tj_warp_sum(v);
  const int lane = threadIdx.x & 31, wid = threadIdx.x >> 5, nw = (blockDim.x + 31) >> 5;
  __syncthreads();
  if (lane == 0) red[wid] = v;
  __syncthreads();
  v = (threadIdx.x < nw) ? red[threadIdx.x] : 0.0f;
  if (wid == 0) v = tj_warp_sum(v);
  if (threadIdx.x == 0) red[0] = v;
  __syncthreads();
  return red[0];
}
__device__ __forceinline__ float tj_block_max(float v, float* red) {
  v = tj_warp_max(v);
  const int lane = threadIdx.x & 31, wid = threadIdx.x >> 5, nw = (blockDim.x + 31) >> 5;
  __syncthreads();
  if (lane == 0) red[wid] = v;
  __syncthreads();
  v = (threadIdx.x < nw) ? red[threadIdx.x] : -INFINITY;
  if (wid == 0) v = tj_warp_max(v);
  if (threadIdx.x == 0) red[0] = v;
  __syncthreads();
  return red[0];
}
"""


@dataclass
class Launch:
    name: str
    grid: tuple[int, int, int]
    block: tuple[int, int, int]
    shared: int = 0


@dataclass
class _Gen:
    k: Kernel
    idx: int
    names: dict[int, str]

    def params(self) -> str:
        ps = [f"const {CTYPE[n.dtype]}* __restrict__ {self.names[id(n)]}_p" for n in self.k.inputs]
        ps += [f"{CTYPE[o.dtype]}* __restrict__ out{j}_p" for j, o in enumerate(self.k.outputs)]
        return ", ".join(ps)


def _load(g: _Gen, n: Node, consumer: Node, iter_shape, idx_vars, local: str | None = None) -> str:
    st = access_strides(n, consumer, iter_shape)
    name = local or g.names[id(n)]
    return f"const float {name} = tj_to_f32({g.names[id(n)]}_p[{index_expr(idx_vars, st)}]);"


def _store(g: _Gen, j: int, o: Node, val: str, index: str) -> str:
    return f"out{j}_p[{index}] = tj_from_f32<{CTYPE[o.dtype]}>({val});"


def _body(g: _Gen, nodes: list[Node], local: dict[int, str] | None = None) -> list[str]:
    names = dict(g.names)
    if local:
        names.update(local)
    out = []
    for n in nodes:
        if n.op in ("transpose", "broadcast_to"):
            out.append(f"const float {g.names[id(n)]} = {names[id(n.inputs[0])]};")
        else:
            out.append(f"const float {g.names[id(n)]} = {emit_expr(n, names, 'cuda')};")
        names[id(n)] = g.names[id(n)]
    return out


