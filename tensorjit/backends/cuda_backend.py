def gen_elementwise(g: _Gen) -> tuple[str, Launch]:
    k = g.k
    shape = k.iter_shape
    numel = math.prod(shape) if shape else 1
    dec, idx = decompose("idx", shape, "i") if shape else ([], [])
    cs = contiguous_strides(shape)
    L = [f'extern "C" __global__ void kernel_{g.idx}({g.params()}) {{']
    L.append(f"  for (long idx = blockIdx.x * (long)blockDim.x + threadIdx.x; idx < {numel}L; idx += (long)gridDim.x * blockDim.x) {{")
    L += ["    " + s for s in dec]
    for n in k.inputs:
        consumer = next((c for c in k.nodes if n in c.inputs), k.nodes[0])
        L.append("    " + _load(g, n, consumer, shape, idx))
    L += ["    " + s for s in _body(g, k.nodes)]
    for j, o in enumerate(k.outputs):
        L.append("    " + _store(g, j, o, g.names[id(o)], index_expr(idx, cs)))
    L += ["  }", "}"]
    block = 256
    grid = max(1, min((numel + block - 1) // block, 4096))
    return "\n".join(L), Launch(f"kernel_{g.idx}", (grid, 1, 1), (block, 1, 1))


