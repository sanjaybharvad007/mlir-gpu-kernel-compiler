# ----------------------------------------------------------------------------


def gen_row(g: _Gen, stages: list[Kernel], rows: tuple, N: int) -> tuple[str, Launch]:
    k = g.k
    nrows = math.prod(rows) if rows else 1
    block = max(32, min(1024, 1 << (N - 1).bit_length())) if N > 1 else 32
    vpt = (N + block - 1) // block
    inside = {id(n) for n in k.nodes}
    escaping = {id(o): j for j, o in enumerate(k.outputs)}
    stage_of = {id(n): si for si, st in enumerate(stages) for n in st.nodes}
    vec_shape = tuple(rows) + (N,)

    def is_vec(n: Node) -> bool:
        return n.shape == vec_shape

    # vec values needed by a later stage live in per-thread register arrays
    temps = [n for si, st in enumerate(stages) for n in st.nodes
             if is_vec(n) and any(stage_of.get(id(u), si) != si for u in n.users if id(u) in inside)]
    temp_idx = {id(n): i for i, n in enumerate(temps)}
    dec, row_idx = decompose("r", rows, "i") if rows else ([], [])
    idx_vec = row_idx + ["n"]

    def vec_ref(n: Node) -> str:
        return f"tmp{temp_idx[id(n)]}[e]" if id(n) in temp_idx else f"tj_to_f32(out{escaping[id(n)]}_p[r * {N} + n])"

    L = [f'extern "C" __global__ void kernel_{g.idx}({g.params()}) {{']
    L.append("  __shared__ float red[32];")
    L.append("  const long r = blockIdx.x;")
    L.append("  const int tid = threadIdx.x;")
    L += ["  " + s for s in dec]
    for i in range(len(temps)):
        L.append(f"  float tmp{i}[{vpt}];")
    scalars = [n for n in k.nodes if not is_vec(n)]
    if scalars:
        L.append("  float " + ", ".join(g.names[id(n)] for n in scalars) + ";")

    def elem_loop(body: list[str]) -> list[str]:
        out = [f"  for (int e = 0; e < {vpt}; ++e) {{", f"    const int n = tid + e * {block};", f"    if (n < {N}) {{"]
        out += ["      " + s for s in body]
        out += ["    }", "  }"]
        return out

    for st_i, st in enumerate(stages):
        L.append(f"  // stage {st_i}: {st.kind} {[n.op for n in st.nodes]}")
        if st.kind == "elementwise" and st.iter_shape == vec_shape:
            body, local = [], {}
            for n in st.inputs:
                consumer = next((c for c in st.nodes if n in c.inputs), st.nodes[0])
                if id(n) in inside:
                    src = vec_ref(n) if is_vec(n) else g.names[id(n)]
                    body.append(f"const float {g.names[id(n)]}_l = {src};")
                else:
                    body.append(_load(g, n, consumer, vec_shape, idx_vec, local=f"{g.names[id(n)]}_l"))
                local[id(n)] = f"{g.names[id(n)]}_l"
            body += _body(g, st.nodes, local)
            for n in st.nodes:
                if id(n) in escaping:
                    body.append(_store(g, escaping[id(n)], n, g.names[id(n)], f"r * {N} + n"))
                elif id(n) in temp_idx:
                    body.append(f"tmp{temp_idx[id(n)]}[e] = {g.names[id(n)]};")
            L += elem_loop(body)
        elif st.kind == "elementwise":  # per-row scalar work, uniform across the block
            idx = row_idx + (["0"] if st.iter_shape == tuple(rows) + (1,) else [])
            local = {}
            for n in st.inputs:
                consumer = next((c for c in st.nodes if n in c.inputs), st.nodes[0])
                if id(n) in inside:
                    local[id(n)] = g.names[id(n)]
                else:
                    L.append("  " + _load(g, n, consumer, st.iter_shape, idx, local=f"{g.names[id(n)]}_s"))
                    local[id(n)] = f"{g.names[id(n)]}_s"
            for n in st.nodes:
                names = dict(g.names)
                names.update(local)
                L.append(f"  {g.names[id(n)]} = {emit_expr(n, names, 'cuda')};")
                local[id(n)] = g.names[id(n)]
                if id(n) in escaping:
                    L.append(f"  if (tid == 0) {_store(g, escaping[id(n)], n, g.names[id(n)], 'r')}")
        elif st.kind == "reduce":
            red = st.anchor
            pos = st.nodes.index(red)
            prologue, epilogue = st.nodes[:pos], st.nodes[pos + 1:]
            x = red.inputs[0]
            init = {"sum": "0.0f", "mean": "0.0f", "max": "-INFINITY"}[red.op]
            body, local = [], {}
            pro_inputs = [i for i in st.inputs if any(i in m.inputs for m in prologue + [red])]
            for n in pro_inputs:
                consumer = next((c for c in prologue if n in c.inputs), red)
                if id(n) in inside:
                    src = vec_ref(n) if is_vec(n) else g.names[id(n)]
                    body.append(f"const float {g.names[id(n)]}_l = {src};")
                else:
                    body.append(_load(g, n, consumer, vec_shape, idx_vec, local=f"{g.names[id(n)]}_l"))
                local[id(n)] = f"{g.names[id(n)]}_l"
            body += _body(g, prologue, local)
            v = g.names[id(x)] if id(x) in {id(m) for m in prologue} else local.get(id(x), g.names[id(x)])
            body.append(f"acc = {'fmaxf(acc, ' + v + ')' if red.op == 'max' else 'acc + ' + v};")
            L.append(f"  {{ float acc = {init};")
            L += elem_loop(body)
            L.append(f"  {g.names[id(red)]} = tj_block_{'max' if red.op == 'max' else 'sum'}(acc, red); }}")
            if red.op == "mean":
                L.append(f"  {g.names[id(red)]} = {g.names[id(red)]} / {float(N)!r}f;")
            if id(red) in escaping:
                L.append(f"  if (tid == 0) {_store(g, escaping[id(red)], red, g.names[id(red)], 'r')}")
            idx = row_idx + (["0"] if red.attrs.get("keepdim") else [])
            local = {id(red): g.names[id(red)]}
            for n in [i for i in st.inputs if i not in pro_inputs]:
                consumer = next((c for c in epilogue if n in c.inputs), epilogue[0])
                if id(n) in inside:
                    local[id(n)] = g.names[id(n)]
                else:
                    L.append("  " + _load(g, n, consumer, red.shape, idx, local=f"{g.names[id(n)]}_e"))
                    local[id(n)] = f"{g.names[id(n)]}_e"
            for n in epilogue:
                names = dict(g.names)
                names.update(local)
                L.append(f"  {g.names[id(n)]} = {emit_expr(n, names, 'cuda')};")
                local[id(n)] = g.names[id(n)]
                if id(n) in escaping:
                    L.append(f"  if (tid == 0) {_store(g, escaping[id(n)], n, g.names[id(n)], 'r')}")
        else:
            raise NotImplementedError(st.kind)
    L.append("}")
    return "\n".join(L), Launch(f"kernel_{g.idx}", (nrows, 1, 1), (block, 1, 1))


