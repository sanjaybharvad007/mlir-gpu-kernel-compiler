"""CUDA C++ backend: fused kernels -> generated CUDA source -> NVRTC -> driver launches.

Kernel shapes produced:

* ``elementwise``  grid-stride loop, compile-time index decomposition, broadcast strides.
* ``row`` / ``reduce``  one thread block per row; the row is split across threads
  (``VPT`` elements per thread held in registers), reductions use warp shuffles +
  one shared-memory round, per-row scalars are uniform across the block.
* ``matmul``  64x64x16 shared-memory tiled GEMM with a 4x4 register micro-tile
  per thread (fp32 accumulate) and the fused epilogue applied in the store loop;
  fp16/bf16 inputs with 16-aligned shapes use a Tensor-Core WMMA variant.

All sizes/strides are literals, every tensor has a compile-time dtype, and the
whole program can be captured into a CUDA graph (``CudaProgram.use_graph``) so
a call is one ``cuGraphLaunch``.  Intermediates live in a planned device arena.

The generated source (including the WMMA path) is also compiled as host C++ in
CI through ``csrc/cuda_host_stub.h`` to catch syntax/type errors without a GPU.
"""
