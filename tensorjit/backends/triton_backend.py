"""Triton backend: fused kernels -> generated Triton source -> GPU.

Generated kernels are specialised to the shapes of the program (every size and
stride is a literal in the source), loaded as a Python module from the cache
directory (so Triton's own compilation cache applies), and matmul tiles are
autotuned on-device with a cost-model-pruned search.

Runs under ``TRITON_INTERPRET=1`` for CPU testing.
"""
from __future__ import annotations

import importlib.util
import math
import os
from dataclasses import dataclass

import torch
import triton

from ..ir import DType, Node
from ..passes import Kernel, Program
from ..runtime import (
    TRITON_CANDIDATES, AutotuneStore, CompiledProgram, MatmulConfig, autotune, cache_dir, content_hash,
    cost_model,
)
from .common import access_strides, contiguous_strides, decompose, emit_expr, index_expr

TL_DTYPE = {DType.f32: "tl.float32", DType.f16: "tl.float16", DType.bf16: "tl.bfloat16", DType.i32: "tl.int32"}

PRELUDE = """\
# generated by tensorjit -- do not edit
import triton
import triton.language as tl
"""


def _interpreting() -> bool:
    return os.environ.get("TRITON_INTERPRET", "0") == "1"


@dataclass
class _Gen:
    k: Kernel
    idx: int
    names: dict[int, str]

    def params(self) -> list[str]:
        return [f"{self.names[id(n)]}_p" for n in self.k.inputs] + [f"out{j}_p" for j in range(len(self.k.outputs))]


def _body(g: _Gen, nodes: list[Node]) -> list[str]:
    out = []
    for n in nodes:
        if n.op in ("transpose", "broadcast_to"):
            out.append(f"{g.names[id(n)]} = {g.names[id(n.inputs[0])]}")
        else:
            out.append(f"{g.names[id(n)]} = {emit_expr(n, g.names, 'triton')}")
    return out


def _load(g: _Gen, n: Node, consumer: Node, iter_shape, idx_vars, mask: str, other: str = "1.0") -> str:
    st = access_strides(n, consumer, iter_shape)
    name = g.names[id(n)]
    return f"{name} = tl.load({name}_p + ({index_expr(idx_vars, st)}), mask={mask}, other={other}).to(tl.float32)"


def _store(j: int, val: str, index: str, mask: str) -> str:
    return f"tl.store(out{j}_p + ({index}), ({val}).to(out{j}_p.dtype.element_ty), mask={mask})"


def gen_elementwise(g: _Gen) -> tuple[str, dict]:
    k = g.k
    shape = k.iter_shape
    numel = math.prod(shape) if shape else 1
    dec, idx = decompose("offs", shape, "i", lang="triton") if shape else ([], [])
    L = ["@triton.jit", f"def kernel_{g.idx}({', '.join(g.params())}, BLOCK: tl.constexpr):"]
    L.append("    pid = tl.program_id(0)")
    L.append("    offs = pid * BLOCK + tl.arange(0, BLOCK)")
    L.append(f"    mask = offs < {numel}")
    L += ["    " + s for s in dec]
    for n in k.inputs:
        consumer = next((c for c in k.nodes if n in c.inputs), k.nodes[0])
        L.append("    " + _load(g, n, consumer, shape, idx, "mask"))
    L += ["    " + s for s in _body(g, k.nodes)]
    for j, o in enumerate(k.outputs):
        L.append("    " + _store(j, g.names[id(o)], "offs", "mask"))
    block = min(1024, max(128, 1 << (numel - 1).bit_length())) if numel > 1 else 1
    meta = {"grid": lambda: (triton.cdiv(numel, block),), "BLOCK": block}
    return "\n".join(L), meta


def gen_reduce(g: _Gen) -> tuple[str, dict]:
    k = g.k
    red = k.anchor
    x = red.inputs[0]
    in_shape = x.shape
    N = in_shape[-1]
    rows = math.prod(in_shape[:-1]) if len(in_shape) > 1 else 1
    pos = k.nodes.index(red)
    prologue, epilogue = k.nodes[:pos], k.nodes[pos + 1:]
    init = {"sum": "0.0", "mean": "0.0", "max": "float('-inf')"}[red.op]
    dec, row_idx = decompose("r", in_shape[:-1], "i", lang="triton") if len(in_shape) > 1 else ([], [])
    idx_in = row_idx + ["n"]
    pro_inputs = [i for i in k.inputs if any(i in m.inputs for m in prologue + [red])]
    epi_inputs = [i for i in k.inputs if i not in pro_inputs]

    L = ["@triton.jit", f"def kernel_{g.idx}({', '.join(g.params())}, BLOCK_N: tl.constexpr):"]
    L.append("    r = tl.program_id(0)")
    L += ["    " + s for s in dec]
    L.append(f"    acc = tl.full([BLOCK_N], {init}, tl.float32)")
    L.append(f"    for n0 in range(0, {N}, BLOCK_N):")
    L.append("        n = n0 + tl.arange(0, BLOCK_N)")
    L.append(f"        m = n < {N}")
    for n in pro_inputs:
        consumer = next((c for c in prologue if n in c.inputs), red)
        L.append("        " + _load(g, n, consumer, in_shape, idx_in, "m", other=init))
    L += ["        " + s for s in _body(g, prologue)]
    v = g.names[id(x)]
    if red.op == "max":
        L.append(f"        acc = tl.maximum(acc, tl.where(m, {v}, float('-inf')))")
    else:
        L.append(f"        acc = acc + tl.where(m, {v}, 0.0)")
    L.append(f"    {g.names[id(red)]} = {'tl.max' if red.op == 'max' else 'tl.sum'}(acc, 0)")
    if red.op == "mean":
        L.append(f"    {g.names[id(red)]} = {g.names[id(red)]} / {float(N)!r}")
    out_idx = row_idx + (["0"] if red.attrs.get("keepdim") else [])
    for n in epi_inputs:
        consumer = next((c for c in epilogue if n in c.inputs), epilogue[0])
        L.append("    " + _load(g, n, consumer, red.shape, out_idx, "True"))
    L += ["    " + s for s in _body(g, epilogue)]
    for j, o in enumerate(k.outputs):
        L.append("    " + _store(j, g.names[id(o)], "r", "True"))
    block_n = min(2048, max(16, 1 << (N - 1).bit_length()))
    meta = {"grid": lambda: (rows,), "BLOCK_N": block_n}
    return "\n".join(L), meta


def gen_matmul(g: _Gen) -> tuple[str, dict]:
    k = g.k
    mm = k.anchor
    a, b = mm.inputs
    M, K = a.shape[-2], a.shape[-1]
    tb = bool(mm.attrs.get("trans_b"))
    N = b.shape[-2] if tb else b.shape[-1]
    out_shape = mm.shape
    batch_shape = out_shape[:-2]
    batch = math.prod(batch_shape) if batch_shape else 1
    epilogue = [n for n in k.nodes if n is not mm]

    def bstrides(t: Node):
        cs = contiguous_strides(t.shape)
        pad = len(batch_shape) - (len(t.shape) - 2)
        st = [0] * pad
        for d in range(len(t.shape) - 2):
            st.append(0 if t.shape[d] == 1 and batch_shape[pad + d] != 1 else cs[d])
        return tuple(st)

    dec, bidx = decompose("bi", batch_shape, "b", lang="triton") if batch_shape else ([], [])
    a_off = index_expr(bidx, bstrides(a)) if batch_shape else "0"
    b_off = index_expr(bidx, bstrides(b)) if batch_shape else "0"
    A, B = g.names[id(a)], g.names[id(b)]
    precision = ', input_precision="ieee"' if a.dtype == DType.f32 and os.environ.get("TENSORJIT_TF32") != "1" else ""

    L = ["@triton.jit"]
    L.append(f"def kernel_{g.idx}({', '.join(g.params())}, TM: tl.constexpr, TN: tl.constexpr, TK: tl.constexpr):")
    L.append("    pid_m = tl.program_id(0)")
    L.append("    pid_n = tl.program_id(1)")
    L.append("    bi = tl.program_id(2)")
    L += ["    " + s for s in dec]
    L.append("    rm = pid_m * TM + tl.arange(0, TM)")
    L.append("    rn = pid_n * TN + tl.arange(0, TN)")
    L.append("    rk = tl.arange(0, TK)")
    L.append(f"    a_base = {A}_p + ({a_off})")
    L.append(f"    b_base = {B}_p + ({b_off})")
    L.append("    acc = tl.zeros([TM, TN], dtype=tl.float32)")
    L.append(f"    for k0 in range(0, {K}, TK):")
    L.append("        kk = k0 + rk")
    L.append(f"        a_t = tl.load(a_base + rm[:, None] * {K} + kk[None, :], mask=(rm[:, None] < {M}) & (kk[None, :] < {K}), other=0.0)")
    if tb:  # B stored [N, K]: read the [TK, TN] tile with swapped strides
        L.append(f"        b_t = tl.load(b_base + kk[:, None] + rn[None, :] * {K}, mask=(kk[:, None] < {K}) & (rn[None, :] < {N}), other=0.0)")
    else:
        L.append(f"        b_t = tl.load(b_base + kk[:, None] * {N} + rn[None, :], mask=(kk[:, None] < {K}) & (rn[None, :] < {N}), other=0.0)")
    L.append(f"        acc += tl.dot(a_t, b_t{precision})")
    L.append(f"    {g.names[id(mm)]} = acc")
    L.append(f"    omask = (rm[:, None] < {M}) & (rn[None, :] < {N})")
    out_idx = bidx + ["rm[:, None]", "rn[None, :]"]
    for n in k.inputs:
        if n is a or n is b:
            continue
        consumer = next((c for c in epilogue if n in c.inputs), epilogue[0])
        L.append("    " + _load(g, n, consumer, out_shape, out_idx, "omask"))
    L += ["    " + s for s in _body(g, epilogue)]
    cs = contiguous_strides(out_shape)
    for j, o in enumerate(k.outputs):
        L.append("    " + _store(j, g.names[id(o)], index_expr(out_idx, cs), "omask"))
    meta = {"shape": (M, N, K), "batch": batch}
    return "\n".join(L), meta


def _load_module(source: str):
    h = content_hash(source, "triton-v1")
    path = cache_dir() / f"tj_triton_{h}.py"
    if not path.exists():
        tmp = path.with_suffix(".tmp")
        tmp.write_text(source)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(f"tj_triton_{h}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


def compile_program(program: Program, device: str = "cuda", tune: bool = True) -> CompiledProgram:
    gens, sources, metas = [], [PRELUDE], []
    for idx, k in enumerate(program.kernels):
        names = {id(n): f"in{j}" for j, n in enumerate(k.inputs)}
        names.update({id(n): f"v{j}" for j, n in enumerate(k.nodes)})
        g = _Gen(k, idx, names)
        gens.append(g)
        if k.kind in ("elementwise", "copy"):
            src, meta = gen_elementwise(g)
        elif k.kind == "reduce":
            src, meta = gen_reduce(g)
        elif k.kind == "row":
            src, meta = gen_row(g)
        elif k.kind == "matmul":
            src, meta = gen_matmul(g)
        else:
            raise NotImplementedError(k.kind)
        sources.append(src)
        metas.append(meta)

    full = "\n\n".join(sources)
    mod = _load_module(full)
    store = AutotuneStore()
    kernel_fns = []
    configs: dict[int, MatmulConfig] = {}
    for g, meta in zip(gens, metas):
        kern = getattr(mod, f"kernel_{g.idx}")
        if g.k.kind == "matmul":
            M, N, K = meta["shape"]
            batch = meta["batch"]
            key = f"triton|matmul|{M}x{N}x{K}|{g.k.anchor.dtype.value}|tb{int(bool(g.k.anchor.attrs.get('trans_b')))}|epi{len(g.k.nodes) - 1}"

            def make_run(cfg: MatmulConfig, kern=kern, M=M, N=N, batch=batch):
                grid = (triton.cdiv(M, cfg.TM), triton.cdiv(N, cfg.TN), batch)

                def run(ins, outs):
                    kern[grid](*ins, *outs, TM=cfg.TM, TN=cfg.TN, TK=cfg.TK, num_warps=cfg.num_warps)

                return run

            if _interpreting() or not tune or os.environ.get("TENSORJIT_NO_AUTOTUNE") == "1":
                cached = store.get(key)
                cfg = MatmulConfig.from_dict(cached["config"]) if cached else min(
                    TRITON_CANDIDATES, key=lambda c: cost_model(c, M, N, K, "triton")
                )
                if _interpreting():  # keep the numpy interpreter fast
                    cfg = MatmulConfig(32, 32, 32, 2)
            else:
                ins = [torch.randn(i.shape, device=device, dtype=_torch_dtype(i.dtype)) for i in g.k.inputs]
                outs = [torch.empty(o.shape, device=device, dtype=_torch_dtype(o.dtype)) for o in g.k.outputs]

                def build(cfg, ins=ins, outs=outs):
                    run = make_run(cfg)

                    def timed():
                        run(ins, outs)
                        torch.cuda.synchronize()

                    return timed

                cfg = autotune(key, TRITON_CANDIDATES, build, (M, N, K), "triton", store=store)
            configs[g.idx] = cfg
            kernel_fns.append(make_run(cfg))
        else:
            grid = meta["grid"]()
            consts = {kk: v for kk, v in meta.items() if kk != "grid"}
            kernel_fns.append(lambda ins, outs, kern=kern, grid=grid, consts=consts: kern[grid](*ins, *outs, **consts))

    cp = CompiledProgram(program, kernel_fns, device, "triton")
    cp.source = full  # type: ignore[attr-defined]
    cp.matmul_configs = configs  # type: ignore[attr-defined]
    return cp


def _torch_dtype(d: DType):
    from ..runtime import TORCH_DTYPE

    return TORCH_DTYPE[d]


