def gen_row(g: _Gen) -> tuple[str, dict]:
    k = g.k
    stages = k.stages  # type: ignore[attr-defined]
    rows, N = tuple(k.rows), k.n  # type: ignore[attr-defined]
    nrows = math.prod(rows) if rows else 1
    inside = {id(n) for n in k.nodes}
    escaping = {id(o): j for j, o in enumerate(k.outputs)}
    vec_shape = rows + (N,)
    dec, row_idx = decompose("r", rows, "i", lang="triton") if rows else ([], [])
    idx_vec = row_idx + ["n"]

    def is_vec(n: Node) -> bool:
        return n.shape == vec_shape

    L = ["@triton.jit", f"def kernel_{g.idx}({', '.join(g.params())}, BLOCK_N: tl.constexpr):"]
    L.append("    r = tl.program_id(0)")
    L += ["    " + s for s in dec]
    L.append("    n = tl.arange(0, BLOCK_N)")
    L.append(f"    m = n < {N}")
    loaded: set[int] = set()
    for st_i, st in enumerate(stages):
        L.append(f"    # stage {st_i}: {st.kind} {[n.op for n in st.nodes]}")
        for n in st.inputs:
            if id(n) in inside or id(n) in loaded:
                continue
            loaded.add(id(n))
            consumer = next((c for c in st.nodes if n in c.inputs), st.nodes[0])
            if is_vec(n) or (len(n.shape) == len(vec_shape) and n.shape[-1] == N) or n.shape == (N,):
                L.append("    " + _load(g, n, consumer, vec_shape, idx_vec, "m", other="0.0"))
            else:  # per-row scalar or broadcast scalar
                shp = st.iter_shape if st.kind != "reduce" else st.anchor.shape
                idx = row_idx + (["0"] if len(shp) == len(rows) + 1 else [])
                L.append("    " + _load(g, n, consumer, shp, idx, "True"))
        if st.kind == "reduce":
            red = st.anchor
            pos = st.nodes.index(red)
            for n in st.nodes[:pos]:
                L.append(f"    {g.names[id(n)]} = {emit_expr(n, g.names, 'triton')}")
            x = g.names[id(red.inputs[0])]
            if red.op == "max":
                L.append(f"    {g.names[id(red)]} = tl.max(tl.where(m, {x}, float('-inf')), 0)")
            else:
                L.append(f"    {g.names[id(red)]} = tl.sum(tl.where(m, {x}, 0.0), 0)")
                if red.op == "mean":
                    L.append(f"    {g.names[id(red)]} = {g.names[id(red)]} / {float(N)!r}")
            rest = st.nodes[pos + 1:]
        else:
            rest = st.nodes
        for n in rest:
            L.append(f"    {g.names[id(n)]} = {emit_expr(n, g.names, 'triton')}")
        for n in st.nodes:
            if id(n) in escaping:
                j = escaping[id(n)]
                if is_vec(n):
                    L.append("    " + _store(j, g.names[id(n)], f"r * {N} + n", "m"))
                else:
                    L.append("    " + _store(j, g.names[id(n)], "r", "True"))
    block_n = max(16, 1 << (N - 1).bit_length())
    meta = {"grid": lambda: (nrows,), "BLOCK_N": block_n}
    return "\n".join(L), meta
